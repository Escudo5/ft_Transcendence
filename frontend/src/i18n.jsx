//Funcion para cambiar interfaz en árabe

const I18nContext = createContext(null);

function getInitialLanguage() {
  const savedLanguage = window.localStorage.getItem(STORAGE_KEY);
  return LANGUAGES[savedLanguage] ? savedLanguage : 'es';
}

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);
  const languageInfo = LANGUAGES[language];

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    document.documentElement.dir = languageInfo.dir;
  }, [language, languageInfo.dir]);

  const value = useMemo(() => ({
    language,
    languageInfo,
    setLanguage,
    t: (key, variables = {}) => {
      const value = translations[language][key] ?? translations.es[key] ?? key;
      return Object.entries(variables).reduce(
        (text, [name, replacement]) => text.replace(`{${name}}`, replacement),
        value,
      );
    },
  }), [language, languageInfo]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n debe usarse dentro de I18nProvider');
  return context;
}

export function LanguageSelector() {
  const { language, languageInfo, setLanguage, t } = useI18n();

  return (
    <label className="language-selector">
      <span className="sr-only">{t('language')}</span>
      <span aria-hidden="true">文</span>
      <select
        value={language}
        aria-label={t('language')}
        onChange={(event) => setLanguage(event.target.value)}
      >
        {Object.entries(LANGUAGES).map(([code, info]) => (
          <option key={code} value={code}>{info.shortLabel} · {info.label}</option>
        ))}
      </select>
    </label>
  );
}
